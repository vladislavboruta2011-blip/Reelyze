// Browser-only, ephemeral handoff between the Analyze form and the
// Results page. Never imports a server-only module (no provider, no
// process.env) — this file must be safe to bundle into client code.
import {
  isValidYouTubeVideoId,
  normalizeYouTubeVideoUrl,
  type YouTubeUrlSourceFormat,
} from "@/lib/competitor-scripts/youtube-url";
import {
  MAX_LANGUAGE_CODE_LENGTH,
  MAX_SEGMENTS,
  MAX_SEGMENT_TEXT_LENGTH,
  MAX_TRANSCRIPT_TEXT_LENGTH,
} from "@/lib/competitor-scripts/transcript/normalize";
import type { TranscriptSegment } from "@/lib/competitor-scripts/transcript/types";

export const ANALYZE_RESULT_STORAGE_KEY =
  "climpy:competitor-analyze-result:v1";

const STORAGE_VERSION = 1;
const MAX_CANONICAL_URL_LENGTH = 2048;
const SOURCE_FORMATS: readonly YouTubeUrlSourceFormat[] = [
  "watch",
  "shorts",
  "short",
];

export type StoredAnalyzeResult = {
  v: 1;
  createdAt: number;
  input: {
    videoId: string;
    canonicalUrl: string;
    sourceFormat: YouTubeUrlSourceFormat;
  };
  transcript: {
    languageCode: string | null;
    isAutoGenerated: boolean | null;
    segments: TranscriptSegment[];
    text: string;
    durationMs: number | null;
  };
};

// The exact safe DTO shape the analyze API returns on success — the input
// this module accepts when writing a fresh result after a real API call.
export type AnalyzeSuccessPayload = {
  input: StoredAnalyzeResult["input"];
  transcript: StoredAnalyzeResult["transcript"];
};

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function isFiniteNumber(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value);
}

function isValidSegment(value: unknown): value is TranscriptSegment {
  if (!isPlainObject(value)) {
    return false;
  }

  const { text, startMs, durationMs } = value;

  return (
    typeof text === "string" &&
    text.length <= MAX_SEGMENT_TEXT_LENGTH &&
    isFiniteNumber(startMs) &&
    startMs >= 0 &&
    (durationMs === null || (isFiniteNumber(durationMs) && durationMs >= 0))
  );
}

// Sessionstorage is user-writable — every field is re-validated from
// scratch, never trusted just because it parsed as JSON. Reuses the same
// bounds the server-side normalizer enforces (lib/competitor-scripts/
// transcript/normalize.ts) so a tampered/oversized payload is rejected
// the same way the API itself would have rejected it.
export function validateStoredAnalyzeResult(
  value: unknown
): StoredAnalyzeResult | null {
  if (!isPlainObject(value)) {
    return null;
  }

  if (value.v !== STORAGE_VERSION) {
    return null;
  }

  if (!isFiniteNumber(value.createdAt)) {
    return null;
  }

  const { input, transcript } = value;

  if (!isPlainObject(input)) {
    return null;
  }

  const { videoId, canonicalUrl, sourceFormat } = input;

  if (typeof videoId !== "string" || !isValidYouTubeVideoId(videoId)) {
    return null;
  }

  if (
    typeof canonicalUrl !== "string" ||
    canonicalUrl.length === 0 ||
    canonicalUrl.length > MAX_CANONICAL_URL_LENGTH
  ) {
    return null;
  }

  const normalizedCanonicalUrl = normalizeYouTubeVideoUrl(canonicalUrl);
  if (
    !normalizedCanonicalUrl.ok ||
    normalizedCanonicalUrl.videoId !== videoId
  ) {
    return null;
  }

  if (
    typeof sourceFormat !== "string" ||
    !SOURCE_FORMATS.includes(sourceFormat as YouTubeUrlSourceFormat)
  ) {
    return null;
  }

  if (!isPlainObject(transcript)) {
    return null;
  }

  const { languageCode, isAutoGenerated, segments, text, durationMs } =
    transcript;

  if (
    languageCode !== null &&
    (typeof languageCode !== "string" ||
      languageCode.length === 0 ||
      languageCode.length > MAX_LANGUAGE_CODE_LENGTH)
  ) {
    return null;
  }

  if (isAutoGenerated !== null && typeof isAutoGenerated !== "boolean") {
    return null;
  }

  if (
    !Array.isArray(segments) ||
    segments.length > MAX_SEGMENTS ||
    !segments.every(isValidSegment)
  ) {
    return null;
  }

  if (typeof text !== "string" || text.length > MAX_TRANSCRIPT_TEXT_LENGTH) {
    return null;
  }

  if (
    durationMs !== null &&
    (!isFiniteNumber(durationMs) || durationMs < 0)
  ) {
    return null;
  }

  return {
    v: STORAGE_VERSION,
    createdAt: value.createdAt,
    input: {
      videoId,
      canonicalUrl,
      sourceFormat: sourceFormat as YouTubeUrlSourceFormat,
    },
    transcript: {
      languageCode,
      isAutoGenerated,
      segments,
      text,
      durationMs,
    },
  };
}

// Never throws — storage may be unavailable (private browsing, disabled
// storage) or hold a malformed/tampered value, and neither case should
// crash the Results page.
export function readStoredAnalyzeResult(): StoredAnalyzeResult | null {
  try {
    const raw = sessionStorage.getItem(ANALYZE_RESULT_STORAGE_KEY);

    if (raw === null) {
      return null;
    }

    return validateStoredAnalyzeResult(JSON.parse(raw));
  } catch {
    return null;
  }
}

// A new successful Analyze submission always overwrites any previous
// result — there is only ever one "most recent" result per tab.
export function writeStoredAnalyzeResult(payload: AnalyzeSuccessPayload): void {
  const result: StoredAnalyzeResult = {
    v: STORAGE_VERSION,
    createdAt: Date.now(),
    input: payload.input,
    transcript: payload.transcript,
  };

  try {
    sessionStorage.setItem(
      ANALYZE_RESULT_STORAGE_KEY,
      JSON.stringify(result)
    );
  } catch {
    // Storage unavailable — the caller's own success/failure flow is the
    // source of truth, not this best-effort persistence step.
  }
}
