// ── Scores ─────────────────────────────────────────────────────────────

function testScores() {
  const negativeScore = baseAnalysis({ scores: { ...STRONG_SCORES, hookScore: -5 } });
  const r1 = validateCompetitorScriptAnalysis({ candidate: negativeScore, transcript: TRANSCRIPT, expectedLocale: "en" });
  check("score below 0 is rejected", !r1.ok && r1.failure.code === "invalid_score");

  const overScore = baseAnalysis({ scores: { ...STRONG_SCORES, hookScore: 101 } });
  const r2 = validateCompetitorScriptAnalysis({ candidate: overScore, transcript: TRANSCRIPT, expectedLocale: "en" });
  check("score above 100 is rejected", !r2.ok && r2.failure.code === "invalid_score");

  const fractionalScore = baseAnalysis({ scores: { ...STRONG_SCORES, hookScore: 80.5 } });
  const r3 = validateCompetitorScriptAnalysis({ candidate: fractionalScore, transcript: TRANSCRIPT, expectedLocale: "en" });
  check("fractional score is rejected", !r3.ok && r3.failure.code === "invalid_score");

  // hook=60, momentum=60, structure=60 -> mean=60; overall=80 -> deviation exactly 20
  const exactlyTwenty: AnalysisScores = { overallScore: 80, hookScore: 60, structureScore: 60, momentumScore: 60 };
  const exactCandidate = baseAnalysis({
    scores: exactlyTwenty,
    verdict: deriveAnalysisVerdict(exactlyTwenty),
    scoreReasons: scoreReasonsFixture(),
  });
  const r4 = validateCompetitorScriptAnalysis({ candidate: exactCandidate, transcript: TRANSCRIPT, expectedLocale: "en" });
  check("overall/component-mean deviation of exactly 20 is accepted", r4.ok);

  const overTwenty: AnalysisScores = { overallScore: 81, hookScore: 60, structureScore: 60, momentumScore: 60 };
  const overCandidate = baseAnalysis({
    scores: overTwenty,
    verdict: deriveAnalysisVerdict(overTwenty),
    scoreReasons: scoreReasonsFixture(),
  });
  const r5 = validateCompetitorScriptAnalysis({ candidate: overCandidate, transcript: TRANSCRIPT, expectedLocale: "en" });
  check("deviation of 21 is rejected", !r5.ok && r5.failure.code === "inconsistent_scores");

  check(
    "verdict Strong is valid for its scores",
    deriveAnalysisVerdict(STRONG_SCORES) === "strong"
  );

  const fakeStrong = baseAnalysis({
    scores: MIXED_SCORES,
    verdict: "strong",
    scoreReasons: scoreReasonsFixture(),
  });
  const r6 = validateCompetitorScriptAnalysis({ candidate: fakeStrong, transcript: TRANSCRIPT, expectedLocale: "en" });
  check("a stated 'strong' verdict that doesn't match derived verdict is rejected", !r6.ok && r6.failure.code === "invalid_verdict");

  check("weak by overall alone", deriveAnalysisVerdict(WEAK_BY_OVERALL_SCORES) === "weak");
  check("weak by two poor components (overall not <=39)", deriveAnalysisVerdict(WEAK_BY_TWO_POOR_SCORES) === "weak");

  // overall=70 (meets strong floor) but hook=50 (<55) -> mixed, not strong
  const mixedBoundary: AnalysisScores = { overallScore: 70, hookScore: 50, structureScore: 60, momentumScore: 70 };
  check(
    "mixed boundary: overall>=70 but hook<55 is Mixed, not Strong",
    deriveAnalysisVerdict(mixedBoundary) === "mixed"
  );
}

