// ── Size ───────────────────────────────────────────────────────────────

function testSize() {
  const exactly6000: NormalizedTranscript = { ...TRANSCRIPT, text: "a".repeat(MAX_ANALYSIS_TRANSCRIPT_CHARACTERS) };
  check("transcript of exactly 6000 chars is accepted", checkAnalysisTranscriptSize(exactly6000).ok);

  const over6000: NormalizedTranscript = { ...TRANSCRIPT, text: "a".repeat(MAX_ANALYSIS_TRANSCRIPT_CHARACTERS + 1) };
  const result = checkAnalysisTranscriptSize(over6000);
  check(
    "transcript of 6001 chars is rejected with a typed transcript_too_long_for_analysis result",
    !result.ok &&
      result.code === "transcript_too_long_for_analysis" &&
      result.maxCharacters === MAX_ANALYSIS_TRANSCRIPT_CHARACTERS &&
      result.actualCharacters === MAX_ANALYSIS_TRANSCRIPT_CHARACTERS + 1
  );

  check(
    "the size check never truncates — actualCharacters always reports the true length",
    checkAnalysisTranscriptSize({ ...TRANSCRIPT, text: "a".repeat(50_000) }).ok === false &&
      (checkAnalysisTranscriptSize({ ...TRANSCRIPT, text: "a".repeat(50_000) }) as { actualCharacters: number }).actualCharacters === 50_000
  );
}

