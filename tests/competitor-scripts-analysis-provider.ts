async function testRealValidatorRejections(): Promise<void> {
  const cases: { name: string; patch: (c: Record<string, unknown>) => void; code: string }[] = [
    {
      name: "invalid verdict (mismatched with derived verdict)",
      patch: (c) => {
        c.verdict = "weak";
      },
      code: "invalid_verdict",
    },
    {
      name: "inconsistent scores (overallScore far from component mean)",
      patch: (c) => {
        (c.scores as Record<string, number>).overallScore = 10;
      },
      code: "inconsistent_scores",
    },
    {
      name: "unsupported evidence (excerpt not an exact transcript substring)",
      patch: (c) => {
        (c.structure as Array<Record<string, unknown>>)[0].evidence = {
          excerpt: "This phrase does not appear anywhere in the transcript.",
          startMs: 0,
          endMs: 3000,
        };
      },
      code: "invalid_evidence",
    },
    {
      name: "unsupported numeric claim (a number absent from the transcript and ungrounded by timing)",
      patch: (c) => {
        (c.structure as Array<Record<string, unknown>>)[0].analysis =
          "This beat lasts about 47 seconds of screen time.";
      },
      code: "unsupported_numeric_claim",
    },
    {
      name: "unsupported performance claim (an observed-fact viewer behavior claim)",
      patch: (c) => {
        (c.structure as Array<Record<string, unknown>>)[0].analysis =
          "Viewers actually watched through this entire section.";
      },
      code: "unsupported_performance_claim",
    },
  ];

  for (const testCase of cases) {
    const candidate = cloneCandidate();
    testCase.patch(candidate);
    const raw = JSON.stringify(candidate);

    const { caller, calls } = createStepCaller([
      { kind: "raw", raw },
      { kind: "raw", raw },
    ]);
    const result = await runCompetitorScriptAnalysis({
      transcript: TRANSCRIPT,
      locale: "en",
      modelCaller: caller,
    });

    check(
      `real validator rejects: ${testCase.name} (exactly 2 calls, never a 3rd)`,
      calls.length === 2
    );
    check(
      `real validator rejects: ${testCase.name} (typed analysis_invalid_response)`,
      result.ok === false && result.code === "analysis_invalid_response"
    );
  }
}

