async function testOversizedTranscriptRejectedBeforeAnyModelCall(): Promise<void> {
  const oversized = padTranscript(MAX_ANALYSIS_TRANSCRIPT_CHARACTERS + 1);
  const { caller, calls } = createStepCaller([]);
  const result = await runCompetitorScriptAnalysis({
    transcript: oversized,
    locale: "en",
    modelCaller: caller,
  });

  check("oversized transcript (6001 chars) makes zero model calls", calls.length === 0);

  const isExpectedFailure =
    !result.ok &&
    result.code === "transcript_too_long_for_analysis" &&
    result.maxCharacters === MAX_ANALYSIS_TRANSCRIPT_CHARACTERS &&
    result.actualCharacters === MAX_ANALYSIS_TRANSCRIPT_CHARACTERS + 1;

  check(
    "oversized transcript returns the typed transcript_too_long_for_analysis failure",
    isExpectedFailure
  );
  check(
    "the transcript_too_long_for_analysis result is exactly checkAnalysisTranscriptSize's own AnalysisSizeCheckResult shape (reused, not a competing duplicate)",
    !result.ok && Object.keys(result).sort().join(",") === "actualCharacters,code,maxCharacters,ok"
  );
}

