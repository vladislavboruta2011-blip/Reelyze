async function testPromptContent(): Promise<void> {
  const prompt = buildSystemPrompt();

  check(
    "prompt restricts grounding to the transcript only",
    prompt.includes("the only source of truth")
  );
  check(
    "prompt prohibits unsupported performance-data claims (views/retention/etc.)",
    prompt.includes("actual views") && prompt.includes("actual retention")
  );
  check(
    "prompt prohibits visual/camera-work analysis (text-only transcript)",
    prompt.includes("camera work") && prompt.includes("cannot see the video")
  );
  check(
    "prompt encodes the quote-verbatim rule",
    prompt.includes("quotation marks mean verbatim") &&
      prompt.includes("MUST be copied exactly from the transcript")
  );
  check(
    "prompt forbids forcing a question-based hook",
    prompt.includes("Do not force a question-based hook")
  );
  check(
    "prompt explicitly permits zero weaknesses for a strong script",
    prompt.includes("can have zero weaknesses")
  );
  check(
    "prompt distinguishes actionable lessons (transferable) from copying/rewriting the script",
    prompt.includes("not a copy or rewrite of this script's specific words")
  );
}

