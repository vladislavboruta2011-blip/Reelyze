async function testRetryPromptDiscipline(): Promise<void> {
  const { caller, calls } = createStepCaller([{ kind: "transient" }, { kind: "raw", raw: validRaw() }]);
  await runCompetitorScriptComparison({
    userScript: USER_SCRIPT,
    competitorTranscript: COMPETITOR_TRANSCRIPT,
    locale: "en",
    modelCaller: caller,
  });

  check(
    "system/instruction prompt is byte-identical across attempt 1 and attempt 2",
    calls[0].systemPrompt === calls[1].systemPrompt
  );
  check(
    "buildSystemPrompt() is a pure function of no arguments (identical output every call)",
    buildSystemPrompt() === buildSystemPrompt()
  );

  const bad = cloneCandidate();
  (bad.dimensionFindings as Array<Record<string, unknown>>)[0].strongerSide = "not-a-real-side";
  const { caller: rejectCaller, calls: rejectCalls } = createStepCaller([
    { kind: "raw", raw: JSON.stringify(bad) },
    { kind: "raw", raw: validRaw() },
  ]);
  await runCompetitorScriptComparison({
    userScript: USER_SCRIPT,
    competitorTranscript: COMPETITOR_TRANSCRIPT,
    locale: "en",
    modelCaller: rejectCaller,
  });
  check(
    "on a validator-rejection retry, the base user prompt is unchanged and only a corrective instruction is appended",
    rejectCalls[1].userPrompt.startsWith(rejectCalls[0].userPrompt) &&
      rejectCalls[1].userPrompt.length > rejectCalls[0].userPrompt.length
  );
}

