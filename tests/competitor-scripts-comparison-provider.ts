// ── Scripted fake model caller (zero real OpenAI calls) ───────────────────

type CallerStep = { kind: "transient" } | { kind: "raw"; raw: string };

function createStepCaller(steps: CallerStep[]): {
  caller: CompetitorComparisonModelCaller;
  calls: { systemPrompt: string; userPrompt: string }[];
} {
  const calls: { systemPrompt: string; userPrompt: string }[] = [];
  let index = 0;

  const caller: CompetitorComparisonModelCaller = async ({ systemPrompt, userPrompt }) => {
    calls.push({ systemPrompt, userPrompt });
    const step = steps[index];
    index += 1;

    if (!step) {
      throw new Error("Test caller invoked a third time — this must never happen.");
    }

    if (step.kind === "transient") {
      throw { status: 500 };
    }

    return { raw: step.raw, modelUsed: COMPETITOR_COMPARISON_MODEL };
  };

  return { caller, calls };
}

