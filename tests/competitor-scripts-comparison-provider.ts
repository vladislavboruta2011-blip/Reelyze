async function testSchemaStrictShape(): Promise<void> {
  const schema = COMPARISON_JSON_SCHEMA as Record<string, unknown> & {
    additionalProperties: boolean;
    required: string[];
    properties: {
      schemaVersion: Record<string, unknown>;
      dimensionFindings: {
        items: {
          additionalProperties: boolean;
          required: string[];
          properties: {
            gap: { anyOf: Array<Record<string, unknown>> };
            evidence: {
              additionalProperties: boolean;
              required: string[];
              properties: {
                competitor: {
                  additionalProperties: boolean;
                  required: string[];
                  properties: { endMs: { type: string[] } };
                };
              };
            };
          };
        };
      };
      cautions: {
        items: {
          properties: {
            evidence: {
              properties: { user: { anyOf: Array<Record<string, unknown>> } };
            };
          };
        };
      };
    };
  };

  check("top-level schema forbids additional properties", schema.additionalProperties === false);
  check(
    "top-level required list has exactly the 6 approved fields, no sourceMeta",
    schema.required.sort().join(",") ===
      "comparisonSummary,cautions,dimensionFindings,locale,priorities,schemaVersion".split(",").sort().join(",")
  );
  check("schemaVersion is a fixed-1 enum, not a free integer", (schema.properties.schemaVersion as { enum: number[] }).enum.join(",") === "1");

  const dimensionSchema = schema.properties.dimensionFindings.items;
  check("dimension-finding object forbids additional properties", dimensionSchema.additionalProperties === false);
  check(
    "dimension-finding evidence object forbids additional properties and requires both sides",
    dimensionSchema.properties.evidence.additionalProperties === false &&
      dimensionSchema.properties.evidence.required.sort().join(",") === "competitor,user"
  );
  check(
    "gap is expressed as a required, nullable anyOf (not an untested type-array+null-enum combination)",
    Array.isArray(dimensionSchema.properties.gap.anyOf) && dimensionSchema.properties.gap.anyOf.length === 2
  );
  check(
    "competitor evidence endMs is a required, nullable integer (type array, matching Analyze's own nullableInteger())",
    dimensionSchema.properties.evidence.properties.competitor.properties.endMs.type.sort().join(",") ===
      "integer,null"
  );
  check(
    "competitor evidence object forbids additional properties",
    dimensionSchema.properties.evidence.properties.competitor.additionalProperties === false
  );

  const cautionSchema = schema.properties.cautions.items;
  check(
    "caution evidence.user is a required, nullable anyOf (mirrors Analyze's nullableEvidenceSchema)",
    Array.isArray(cautionSchema.properties.evidence.properties.user.anyOf) &&
      cautionSchema.properties.evidence.properties.user.anyOf.length === 2
  );
}

