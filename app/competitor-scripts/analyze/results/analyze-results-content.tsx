"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { ArrowRight, GitCompare, Sparkles } from "lucide-react";
import type { Messages } from "../../../../lib/messages";
import {
  readStoredAnalyzeResult,
  type StoredAnalyzeResult,
} from "../../../../lib/competitor-scripts/analyze-result-storage";
import { CautionSection } from "./caution-section";
import { LessonsSection } from "./lessons-section";
import { MainTakeaway } from "./main-takeaway";
import { ResultsSummary } from "./results-summary";
import { RisksSection } from "./risks-section";
import { ScoreOverview } from "./score-overview";
import { ScriptBreakdown } from "./script-breakdown";
import { StrengthsSection } from "./strengths-section";
import { TranscriptSection } from "./transcript-section";
import { WeaknessesSection } from "./weaknesses-section";
import { WhyScoresSection } from "./why-scores-section";

type ResultsCopy = Messages["competitorScripts"]["analyzeResults"];

type ContentState =
  | { status: "loading" }
  | { status: "missing" }
  | { status: "ready"; result: StoredAnalyzeResult };

// The one client boundary on the Results page. sessionStorage is only
// ever readable after mount, so this always starts in "loading" on both
// the server render and the client's first render (avoiding a hydration
// mismatch), then resolves to "missing" or "ready" from a single
// mount-only effect. The illustrative score/analysis report (everything
// from the preview notice down) only ever renders in the "ready" branch
// — a missing or tampered/invalid stored result shows the empty state
// instead, never a silent fallback to fake data.
export function AnalyzeResultsContent({ copy }: { copy: ResultsCopy }) {
  const [state, setState] = useState<ContentState>({ status: "loading" });

  useEffect(() => {
    // Deferred via a same-tick timer, matching the repo's existing
    // sessionStorage-hydration convention (see app/results/page.tsx) — a
    // setState call directly in an effect body is flagged by
    // react-hooks/set-state-in-effect.
    const timer = window.setTimeout(() => {
      const result = readStoredAnalyzeResult();
      setState(result ? { status: "ready", result } : { status: "missing" });
    }, 0);

    return () => window.clearTimeout(timer);
  }, []);

  if (state.status === "loading") {
    return (
      <div
        role="status"
        aria-live="polite"
        className="mt-5 rounded-[24px] border border-white/10 bg-white/[0.02] px-6 py-10 text-center"
      >
        <p className="text-[14px] text-[#9CA3AF]">{copy.description}</p>
      </div>
    );
  }

  if (state.status === "missing") {
    return (
      <div className="mt-5 rounded-[24px] border border-white/10 bg-white/[0.02] px-6 py-12 text-center">
        <h2 className="text-[20px] font-semibold text-[#F5F5F7]">
          {copy.missingState.heading}
        </h2>
        <p className="mx-auto mt-3 max-w-[480px] text-[14px] leading-[1.6] text-[#9CA3AF]">
          {copy.missingState.description}
        </p>
        <Link
          href="/competitor-scripts/analyze"
          className="mt-6 inline-flex h-[50px] items-center justify-center gap-2 rounded-[14px] bg-gradient-to-r from-[#6D28D9] to-[#7C3AED] px-6 text-[14px] font-semibold text-white transition hover:from-[#7C3AED] hover:to-[#8B5CF6] focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#C4B5FD]"
        >
          {copy.missingState.action}
          <ArrowRight size={16} aria-hidden="true" />
        </Link>
      </div>
    );
  }

  const { result } = state;
  const summaryData = {
    videoId: result.input.videoId,
    canonicalUrl: result.input.canonicalUrl,
    sourceFormat: result.input.sourceFormat,
    languageCode: result.transcript.languageCode,
    durationMs: result.transcript.durationMs,
    segmentCount: result.transcript.segments.length,
  };
  const transcriptData = {
    languageCode: result.transcript.languageCode,
    isAutoGenerated: result.transcript.isAutoGenerated,
    durationMs: result.transcript.durationMs,
    segments: result.transcript.segments,
    text: result.transcript.text,
  };

  return (
    <div className="flex flex-col gap-3">
      <div className="mt-5 flex items-start gap-2.5 rounded-[14px] border border-[#7C3AED]/30 bg-[#7C3AED]/10 px-4 py-3">
        <Sparkles
          size={16}
          className="mt-0.5 shrink-0 text-[#C4B5FD]"
          aria-hidden="true"
        />
        <p className="text-[13px] leading-[1.5] text-[#C4B5FD]">
          {copy.previewNotice}
        </p>
      </div>

      <SectionGroupLabel label={copy.sectionGroups.realData} />

      <ResultsSummary summary={copy.summary} data={summaryData} />

      <TranscriptSection copy={copy.transcript} data={transcriptData} />

      <SectionGroupLabel label={copy.sectionGroups.exampleAnalysis} />

      <div className="flex flex-col gap-5 lg:gap-7">
        <ScoreOverview scores={copy.scores} />

        <MainTakeaway takeaway={copy.takeaway} />

        <WhyScoresSection whyScores={copy.whyScores} />

        <ScriptBreakdown timeline={copy.timeline} />

        <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
          <StrengthsSection strengths={copy.strengths} />
          <WeaknessesSection weaknesses={copy.weaknesses} />
        </div>

        <div className="grid grid-cols-1 gap-5 lg:grid-cols-[1fr_1.15fr]">
          <RisksSection risks={copy.risks} />
          <LessonsSection lessons={copy.lessons} />
        </div>

        <CautionSection caution={copy.caution} />

        <div className="mt-2 flex flex-col gap-4 border-t border-white/10 pt-6 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex flex-col gap-1 sm:flex-row sm:items-center sm:gap-5">
            <Link
              href="/competitor-scripts/analyze"
              className="inline-flex h-[44px] items-center justify-center px-1 text-[13px] font-medium text-[#9CA3AF] transition hover:text-[#F5F5F7] sm:h-auto sm:px-0"
            >
              {copy.actions.backToAnalyze}
            </Link>
            <Link
              href="/competitor-scripts"
              className="inline-flex h-[44px] items-center justify-center px-1 text-[13px] font-medium text-[#9CA3AF] transition hover:text-[#F5F5F7] sm:h-auto sm:px-0"
            >
              {copy.actions.backToSelection}
            </Link>
          </div>

          <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
            <Link
              href="/competitor-scripts/compare"
              className="inline-flex h-[48px] w-full items-center justify-center gap-2 rounded-[14px] border border-white/15 bg-white/[0.03] px-6 text-[14px] font-semibold text-[#F5F5F7] transition hover:bg-white/[0.06] focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#C4B5FD] sm:w-auto"
            >
              <GitCompare size={16} aria-hidden="true" />
              {copy.actions.compareWithMyScript}
            </Link>
            <Link
              href="/competitor-scripts/analyze"
              className="inline-flex h-[48px] w-full items-center justify-center gap-2 rounded-[14px] bg-gradient-to-r from-[#6D28D9] to-[#7C3AED] px-6 text-[14px] font-semibold text-white transition hover:from-[#7C3AED] hover:to-[#8B5CF6] focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#C4B5FD] sm:w-auto"
            >
              {copy.actions.analyzeAnother}
              <ArrowRight size={16} aria-hidden="true" />
            </Link>
          </div>
        </div>
      </div>
    </div>
  );
}

// A minimal divider+label, reused for both the real-data → illustrative
// transition — the one seam the whole redesign hinges on being obvious.
function SectionGroupLabel({ label }: { label: string }) {
  return (
    <div className="mt-2 flex items-center gap-3">
      <span
        className="h-px flex-1 bg-white/10"
        aria-hidden="true"
      />
      <span className="text-[11px] font-semibold uppercase tracking-[0.14em] text-[#6B7280]">
        {label}
      </span>
      <span
        className="h-px flex-1 bg-white/10"
        aria-hidden="true"
      />
    </div>
  );
}
