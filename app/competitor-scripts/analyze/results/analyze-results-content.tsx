"use client";

import { useEffect, useState } from "react";
import Link from "next/link";
import { ArrowRight, GitCompare } from "lucide-react";
import type { Messages } from "../../../../lib/messages";
import {
  readStoredAnalyzeResult,
  type StoredAnalyzeResult,
} from "../../../../lib/competitor-scripts/analyze-result-storage";
import {
  AnalysisUnavailableSection,
  type AnalysisUnavailableReason,
} from "./analysis-unavailable-section";
import { CautionSection } from "./caution-section";
import { LessonsSection } from "./lessons-section";
import { ResultsSummary } from "./results-summary";
import { RisksSection } from "./risks-section";
import { ScoreOverview } from "./score-overview";
import { ScriptBreakdown } from "./script-breakdown";
import { StrengthsSection } from "./strengths-section";
import { TranscriptSection } from "./transcript-section";
import { WeaknessesSection } from "./weaknesses-section";
import { WhyScoresSection } from "./why-scores-section";

type ResultsCopy = Messages["competitorScripts"]["analyzeResults"];

type ContentState =
  | { status: "loading" }
  | { status: "missing" }
  | { status: "ready"; result: StoredAnalyzeResult };

// A legacy (PR9-era) stored payload and a current-shape payload whose
// analysis genuinely didn't complete both resolve to a safe unavailable
// state here — never fabricated analysis content either way.
function resolveUnavailableReason(
  result: StoredAnalyzeResult
): AnalysisUnavailableReason | null {
  if (result.analysis !== null) {
    return null;
  }

  if (result.isLegacy) {
    return "legacy";
  }

  return result.analysisError ?? "analysis_unavailable";
}

// The one client boundary on the Results page. sessionStorage is only
// ever readable after mount, so this always starts in "loading" on both
// the server render and the client's first render (avoiding a hydration
// mismatch), then resolves to "missing" or "ready" from a single
// mount-only effect. This performs no network request of its own — the
// analysis (like the transcript) was already fetched once, during the
// original Analyze submission, and is only ever read back from
// sessionStorage here.
export function AnalyzeResultsContent({ copy }: { copy: ResultsCopy }) {
  const [state, setState] = useState<ContentState>({ status: "loading" });

  useEffect(() => {
    // Deferred via a same-tick timer, matching the repo's existing
    // sessionStorage-hydration convention (see app/results/page.tsx) — a
    // setState call directly in an effect body is flagged by
    // react-hooks/set-state-in-effect.
    const timer = window.setTimeout(() => {
      const result = readStoredAnalyzeResult();
      setState(result ? { status: "ready", result } : { status: "missing" });
    }, 0);

    return () => window.clearTimeout(timer);
  }, []);

  if (state.status === "loading") {
    return (
      <div
        role="status"
        aria-live="polite"
        className="mt-5 rounded-[24px] border border-[#E5E7EB] bg-white px-6 py-10 text-center"
      >
        <p className="text-[14px] text-[#6B7280]">{copy.description}</p>
      </div>
    );
  }

  if (state.status === "missing") {
    return (
      <div className="mt-5 rounded-[24px] border border-[#E5E7EB] bg-white px-6 py-12 text-center">
        <h2 className="text-[20px] font-semibold text-[#111827]">
          {copy.missingState.heading}
        </h2>
        <p className="mx-auto mt-3 max-w-[480px] text-[14px] leading-[1.6] text-[#6B7280]">
          {copy.missingState.description}
        </p>
        <Link
          href="/competitor-scripts/analyze"
          className="mt-6 inline-flex h-[50px] items-center justify-center gap-2 rounded-[14px] bg-gradient-to-r from-[#6D28D9] to-[#7C3AED] px-6 text-[14px] font-semibold text-white transition hover:from-[#7C3AED] hover:to-[#8B5CF6] focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#7C3AED]"
        >
          {copy.missingState.action}
          <ArrowRight size={16} aria-hidden="true" />
        </Link>
      </div>
    );
  }

  const { result } = state;
  const summaryData = {
    videoId: result.input.videoId,
    canonicalUrl: result.input.canonicalUrl,
    sourceFormat: result.input.sourceFormat,
    languageCode: result.transcript.languageCode,
    durationMs: result.transcript.durationMs,
    segmentCount: result.transcript.segments.length,
  };
  const transcriptData = {
    languageCode: result.transcript.languageCode,
    isAutoGenerated: result.transcript.isAutoGenerated,
    durationMs: result.transcript.durationMs,
    segments: result.transcript.segments,
    text: result.transcript.text,
  };
  const unavailableReason = resolveUnavailableReason(result);
  const analysis = result.analysis;
  // Only a direct read of the already-validated analysis fields — never a
  // second, separately-derived source of truth. null whenever analysis
  // itself is null (degraded/legacy), so ResultsSummary's overview panel
  // simply doesn't render rather than showing anything fabricated.
  const analysisOverview =
    analysis === null
      ? null
      : {
          verdict: analysis.verdict,
          scores: analysis.scores,
          mainTakeaway: analysis.mainTakeaway,
        };

  // The dedicated result-entrance class below plays once, right here, the
  // moment this "ready" container is first mounted (i.e. the moment real
  // data is actually on screen) — never on the earlier "loading"
  // placeholder above. This div is the one stable node for the whole
  // ready/degraded report: child disclosure toggles (Show details, Show
  // full structure, Show full transcript, Show all segments, ...) only
  // ever change state inside their own child components, never this
  // component's own state, so this node is never remounted/re-keyed by
  // them and the CSS animation never replays.
  return (
    <div className="flex flex-col gap-3 animate-result-enter">
      <ResultsSummary
        summary={copy.summary}
        scores={copy.scores}
        verdictCopy={copy.verdict}
        takeawayCopy={copy.takeaway}
        data={summaryData}
        analysisOverview={analysisOverview}
      />

      <div className="flex flex-col gap-5 lg:gap-7">
        {unavailableReason !== null || analysis === null ? (
          <AnalysisUnavailableSection
            copy={copy.analysisUnavailable}
            reason={unavailableReason ?? "analysis_unavailable"}
          />
        ) : (
          <>
            {/* MainTakeaway (verdict + mainTakeaway) is intentionally not
                rendered here — it's already shown in the Analysis Overview
                panel inside ResultsSummary above. Rendering it a second
                time here would duplicate the same real data. The
                MainTakeaway component itself is left in place, unused,
                rather than deleted. */}
            <ScoreOverview scores={copy.scores} data={analysis.scores} />

            <WhyScoresSection
              whyScores={copy.whyScores}
              scores={copy.scores}
              reasons={analysis.scoreReasons}
            />

            <ScriptBreakdown
              structureCopy={copy.structure}
              beats={analysis.structure}
            />

            <div className="grid grid-cols-1 gap-5 lg:grid-cols-2">
              <StrengthsSection
                strengths={copy.strengths}
                items={analysis.strengths}
              />
              <WeaknessesSection
                weaknesses={copy.weaknesses}
                severity={copy.severity}
                items={analysis.weaknesses}
              />
            </div>

            <div className="grid grid-cols-1 gap-5 lg:grid-cols-[1fr_1.15fr]">
              <RisksSection
                risks={copy.risks}
                severity={copy.severity}
                items={analysis.retentionRisks}
              />
              <LessonsSection
                lessons={copy.lessons}
                items={analysis.actionableLessons}
              />
            </div>

            <CautionSection caution={copy.caution} items={analysis.caution} />
          </>
        )}

        <TranscriptSection copy={copy.transcript} data={transcriptData} />

        <div className="mt-2 flex flex-col gap-4 border-t border-[#E5E7EB] pt-6 sm:flex-row sm:items-center sm:justify-between">
          <div className="flex flex-col gap-1 sm:flex-row sm:items-center sm:gap-5">
            <Link
              href="/competitor-scripts/analyze"
              className="inline-flex h-[44px] items-center justify-center px-1 text-[13px] font-medium text-[#6B7280] transition hover:text-[#111827] sm:h-auto sm:px-0"
            >
              {copy.actions.backToAnalyze}
            </Link>
            <Link
              href="/competitor-scripts"
              className="inline-flex h-[44px] items-center justify-center px-1 text-[13px] font-medium text-[#6B7280] transition hover:text-[#111827] sm:h-auto sm:px-0"
            >
              {copy.actions.backToSelection}
            </Link>
          </div>

          <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
            <Link
              href="/competitor-scripts/compare"
              className="inline-flex h-[48px] w-full items-center justify-center gap-2 rounded-[14px] border border-[#E5E7EB] bg-white px-6 text-[14px] font-semibold text-[#111827] transition hover:bg-[#F3F4F6] focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#7C3AED] sm:w-auto"
            >
              <GitCompare size={16} aria-hidden="true" />
              {copy.actions.compareWithMyScript}
            </Link>
            <Link
              href="/competitor-scripts/analyze"
              className="inline-flex h-[48px] w-full items-center justify-center gap-2 rounded-[14px] bg-gradient-to-r from-[#6D28D9] to-[#7C3AED] px-6 text-[14px] font-semibold text-white transition hover:from-[#7C3AED] hover:to-[#8B5CF6] focus-visible:outline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-[#7C3AED] sm:w-auto"
            >
              {copy.actions.analyzeAnother}
              <ArrowRight size={16} aria-hidden="true" />
            </Link>
          </div>
        </div>
      </div>
    </div>
  );
}
